export function getCurrencyInfo(code) {
  if (!code) {
    return { code: 'USD', name: 'US Dollar', symbol: '$', popular: true };
  }
  const cleanCode = code.toUpperCase().trim();
  const found = CURRENCIES.find(c => c.code === cleanCode);
  if (found) return found;
  return {
    code: cleanCode,
    name: cleanCode,
    symbol: cleanCode,
    popular: false
  };
}
